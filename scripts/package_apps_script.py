#!/usr/bin/env python3
"""Build a deterministic, inspectable Google Apps Script project package.

The repository keeps source modules as plain JavaScript for testability. Apps Script
projects imported through the editor/clasp use .gs/.json files, so this builder
concatenates the explicitly ordered global-script modules into Code.gs.
It does not deploy or access Google services.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "apps-script" / "src"
MANIFEST = ROOT / "apps-script" / "appsscript.json"
OUTPUT_DEFAULT = ROOT / "dist" / "apps-script"
MODULE_ORDER = (
    "identity.js",
    "authorization.js",
    "validation.js",
    "sheetsRepository.js",
    "audit.js",
    "idempotency.js",
    "whatsappSheetsStore.js",
    "whatsappRegistration.js",
    "service.js",
    "entrypoints.js",
)
REQUIRED_ENTRYPOINTS = (
    "reclaimGetMyOrganizationSummary",
    "reclaimSetOrganizationServiceEnabled",
    "reclaimCreateCollectionSite",
    "reclaimGetCollectionSite",
    "reclaimListCollectionSites",
    "reclaimUpdateCollectionSite",
    "reclaimDeactivateCollectionSite",
    "reclaimRecordCollection",
    "reclaimGetCollectionRecord",
    "reclaimListCollectionRecords",
    "reclaimRecordCollectionHandover",
    "reclaimCreateCustomerRegistration",
    "reclaimGetCustomerRegistration",
    "reclaimListCustomerRegistrations",
)
FORBIDDEN_PATTERNS = (
    (re.compile(r"\brequire\s*\("), "CommonJS require() is not supported in the Apps Script package"),
    (re.compile(r"\bmodule\s*\.\s*exports\b"), "CommonJS module.exports is not supported"),
    (re.compile(r"\bprocess\s*\."), "Node.js process API is not supported"),
    (re.compile(r"\bimport\s+(?:.+\s+from\s+)?['\"]"), "ES module imports are not supported in the generated global script"),
    (re.compile(r"\bexport\s+(?:default\s+)?(?:function|const|let|var|class)\b"), "ES module exports are not supported in the generated global script"),
)
SECRET_PATTERNS = (
    re.compile(r"(?i)AIza[0-9A-Za-z_-]{30,}"),
    re.compile(r"(?i)-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----"),
    re.compile(r"(?i)(?:access_token|refresh_token|client_secret)\s*[:=]\s*['\"][^'\"]{8,}"),
)


def fail(message: str) -> None:
    raise SystemExit(f"Apps Script package error: {message}")


def load_manifest() -> dict:
    try:
        data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail(f"cannot read valid manifest: {exc}")
    if not isinstance(data, dict):
        fail("manifest root must be a JSON object")
    if data.get("runtimeVersion") != "V8":
        fail("runtimeVersion must be V8")
    if not isinstance(data.get("timeZone"), str) or not data["timeZone"].strip():
        fail("timeZone is required")
    scopes = data.get("oauthScopes")
    if not isinstance(scopes, list) or not scopes:
        fail("explicit least-privilege oauthScopes must be declared")
    allowed_scopes = {
        "https://www.googleapis.com/auth/spreadsheets",
        "https://www.googleapis.com/auth/userinfo.email",
    }
    if any(scope not in allowed_scopes for scope in scopes):
        fail("manifest contains a scope not approved by this packaging gate")
    if not allowed_scopes.issubset(set(scopes)):
        fail("manifest must declare Sheets access and user email identity scopes")
    if data.get("webapp", {}).get("access") == "ANYONE_ANONYMOUS":
        fail("anonymous web-app access is prohibited")
    return data


def build(output: Path) -> Path:
    output = output.resolve()
    root = ROOT.resolve()
    dist_root = (root / "dist").resolve()
    if (root / "dist").is_symlink() or dist_root not in output.parents:
        fail("output must be a child directory beneath the repository dist/ directory")
    if SOURCE_DIR.resolve() in output.parents or output == SOURCE_DIR.resolve():
        fail("output cannot be inside the source directory")
    manifest = load_manifest()

    chunks = ["// Generated by scripts/package_apps_script.py; do not edit this file directly.\n"]
    for name in MODULE_ORDER:
        path = SOURCE_DIR / name
        if not path.is_file():
            fail(f"required source module is missing: {path.relative_to(ROOT)}")
        text = path.read_text(encoding="utf-8")
        for pattern, message in FORBIDDEN_PATTERNS:
            if pattern.search(text):
                fail(f"{path.relative_to(ROOT)}: {message}")
        for pattern in SECRET_PATTERNS:
            if pattern.search(text):
                fail(f"possible secret detected in {path.relative_to(ROOT)}")
        chunks.append(f"\n// ---- BEGIN {name} ----\n{text.rstrip()}\n// ---- END {name} ----\n")

    code = "".join(chunks)
    for entrypoint in REQUIRED_ENTRYPOINTS:
        if not re.search(rf"function\s+{re.escape(entrypoint)}\s*\(", code):
            fail(f"required entry point is missing: {entrypoint}")
    if re.search(r"function\s+do(?:Get|Post)\s*\(", code):
        fail("public doGet/doPost web-app entry points are not approved for this stage")

    # Re-serialize in a stable format; keys are sorted for deterministic output.
    manifest_text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    if output.exists():
        if output.is_symlink() or not output.is_dir():
            fail("existing output path must be a regular directory")
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / "Code.gs").write_text(code, encoding="utf-8", newline="\n")
    (output / "appsscript.json").write_text(manifest_text, encoding="utf-8", newline="\n")
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT_DEFAULT, help="package directory (must remain inside the repository)")
    args = parser.parse_args()
    output = build(args.output)
    print(f"Package prepared: {output.relative_to(ROOT.resolve())}")
    print("Files: Code.gs, appsscript.json")
    print("No Google project was accessed; no deployment was performed.")


if __name__ == "__main__":
    main()
